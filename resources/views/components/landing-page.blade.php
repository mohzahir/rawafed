        document.addEventListener("DOMContentLoaded", () => {
            const titleSelect = document.getElementById('calc-title');
            const yearsInput = document.getElementById('calc-years');
            const yearsDisplay = document.getElementById('calc-years-display');
            const minSalaryEl = document.getElementById('calc-salary-min');
            const maxSalaryEl = document.getElementById('calc-salary-max');

            // بيانات تقديرية للرواتب (الحد الأدنى والأعلى لكل تصنيف + الزيادة السنوية للخبرة)
            // الأرقام بالريال السعودي للتوضيح
            const salaryData = {
                'resident':   { minBase: 8000,  maxBase: 12000, increment: 300 },
                'specialist': { minBase: 15000, maxBase: 25000, increment: 800 },
                'consultant': { minBase: 35000, maxBase: 50000, increment: 1500 },
                'nurse':      { minBase: 4000,  maxBase: 8000,  increment: 200 }
            };

            // دالة تنسيق الأرقام بوضع فواصل الآلاف
            const formatNumber = (num) => {
                return num.toString().replace(/\B(?=(\d{3})+(?!\d))/g, ",");
            };

            // دالة الحساب وتحديث الواجهة
            const calculateSalary = () => {
                const title = titleSelect.value;
                const years = parseInt(yearsInput.value);
                
                // تحديث رقم السنوات الظاهر
                yearsDisplay.innerText = years;

                // جلب بيانات التخصص المختار
                const data = salaryData[title];
                
                // حساب الراتب (الأساسي + الزيادة بناءً على الخبرة)
                const calculatedMin = data.minBase + (years * data.increment);
                const calculatedMax = data.maxBase + (years * data.increment * 1.2); // الحد الأعلى يرتفع بنسبة أكبر مع الخبرة

                // تطبيق تأثير وميض خفيف (Pulse) عند تغير الأرقام لإعطاء إحساس بالتفاعل
                minSalaryEl.classList.add('opacity-50', 'scale-95');
                maxSalaryEl.classList.add('opacity-50', 'scale-95');

                setTimeout(() => {
                    minSalaryEl.innerText = formatNumber(Math.round(calculatedMin));
                    maxSalaryEl.innerText = formatNumber(Math.round(calculatedMax));
                    
                    minSalaryEl.classList.remove('opacity-50', 'scale-95');
                    maxSalaryEl.classList.remove('opacity-50', 'scale-95');
                }, 150);
            };

            // الاستماع لتغييرات المستخدم
            titleSelect.addEventListener('change', calculateSalary);
            yearsInput.addEventListener('input', calculateSalary);

            // تشغيل الحساب مرة واحدة عند تحميل الصفحة لضبط الأرقام الافتراضية
            calculateSalary();
        });
