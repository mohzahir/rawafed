    <script>
        document.addEventListener("DOMContentLoaded", () => {
            const counters = document.querySelectorAll('.stat-counter');
            const speed = 50; // التحكم في سرعة العد (رقم أقل = أسرع)

            const animateCounters = () => {
                counters.forEach(counter => {
                    const updateCount = () => {
                        const target = +counter.getAttribute('data-target');
                        const count = +counter.innerText;
                        
                        // زيادة تدريجية متناسبة مع الرقم النهائي
                        const inc = target / speed;

                        if (count < target) {
                            counter.innerText = Math.ceil(count + inc);
                            setTimeout(updateCount, 30); // التحديث كل 30 ملي ثانية
                        } else {
                            counter.innerText = target; // التأكد من الوقوف عند الرقم الدقيق
                        }
                    };
                    updateCount();
                });
            };

            // استخدام IntersectionObserver لضمان بدء العد فقط عندما يصل المستخدم للقسم
            const observerOptions = {
                root: null,
                rootMargin: '0px',
                threshold: 0.5 // يبدأ العد عندما يظهر 50% من القسم في الشاشة
            };

            const observer = new IntersectionObserver((entries, observer) => {
                entries.forEach(entry => {
                    if (entry.isIntersecting) {
                        animateCounters();
                        observer.unobserve(entry.target); // إيقاف المراقبة بعد أن يعمل العد مرة واحدة
                    }
                });
            }, observerOptions);

            const statsSection = document.getElementById('stats-section');
            if (statsSection) {
                observer.observe(statsSection);
            }
        });
    </script>

    

